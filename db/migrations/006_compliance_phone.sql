-- Комплаенс: телефона офицера в материалах архива нет — честная оговорка вместо пустого места (доп. ТЗ, п. 2).
-- Для уже заполненной базы; новая база получает текст из db/seed/data/pages.json. Правка админом не перезаписывается.
update pages
set body = jsonb_set(body, '{ru}', to_jsonb(replace(body->>'ru',
      '**Комплаенс-офицер:** Ешенгельдиев Тырек Молболович.',
      E'**Комплаенс-офицер:** Ешенгельдиев Тырек Молболович.\n\n**Телефон комплаенс-офицера** уточняется у архива. До уточнения — приёмная: [8 (7232) 25-59-76](tel:+77232255976).'))),
    updated_at = now()
where slug = 'compliance' and position('Телефон комплаенс' in body->>'ru') = 0;
