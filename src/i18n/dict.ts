export const LANGS = ["kk", "ru", "en"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "ru";
export const isLang = (x: string): x is Lang => (LANGS as readonly string[]).includes(x);

export type L10n = Partial<Record<Lang, string>>;

// Берёт текст на нужном языке; если перевода нет — русский оригинал и флаг fallback.
export function pick(v: L10n | null | undefined, lang: Lang): { text: string; fallback: boolean } {
  if (!v) return { text: "", fallback: false };
  if (v[lang]) return { text: v[lang]!, fallback: false };
  return { text: v.ru ?? v.kk ?? v.en ?? "", fallback: lang !== "ru" };
}
export const t = (v: L10n | null | undefined, lang: Lang) => pick(v, lang).text;

